<p>Ограничения span следуют из того, что это <code>ref struct</code>, живущий только на стеке: его нельзя хранить в поле класса, захватывать в лямбду или держать через <code>await</code>, класть в коллекцию. Для таких случаев есть <code>Memory&lt;T&gt;</code>. Короткие временные буферы можно выделять на стеке: <code>Span&lt;int&gt; count = stackalloc int[26];</code> — без нагрузки на GC (но только небольшие и фиксированные по размеру, иначе есть риск переполнить стек).</p>

